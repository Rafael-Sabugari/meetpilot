export type Locale = "en" | "pt";

export function detectLocale(lang: string | undefined): Locale {
  return lang?.toLowerCase().startsWith("pt") ? "pt" : "en";
}

export function makeT(locale: Locale) {
  const dict: Record<MessageKey, string> = locale === "pt" ? pt : en;
  return (key: MessageKey): string => dict[key] ?? en[key];
}

